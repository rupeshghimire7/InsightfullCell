/** Save JSON the page already holds as a file (no request): a blob link, clicked once. */
export function saveJson(filename: string, value: unknown): void {
  const blob = new Blob([JSON.stringify(value, null, 2)], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  link.rel = "noopener";
  document.body.append(link);
  link.click();
  link.remove();
  // Revoked after the click has been handled.
  setTimeout(() => URL.revokeObjectURL(url), 0);
}

/** A file name from a title: lower case letters, digits and dashes. */
export function slug(text: string, fallback = "chart"): string {
  const base = text
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60)
    .replace(/-+$/g, "");
  return base || fallback;
}
